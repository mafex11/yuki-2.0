"""What the window's buttons do: one interface the pages call, implemented by the window's controller.

The pages only say what the user asked for ("revoke rule:12", "the user says:
'Elsa is my friend' about Elsa"); the controller (:mod:`yuki.ui.window.app`) does it
through :class:`~yuki.memory.api.MemoryClient`, the settings files or the pipe
to yuki-ui, then reloads what changed. The base class does nothing, so the
offscreen mockups build the same pages with no side effects.
"""

from __future__ import annotations

from typing import Any


class Actions:
    """Every action a page can ask for. Overridden by the live controller; no-ops here."""

    # navigation and feedback
    def navigate(self, page: str) -> None: ...
    def toast(self, text: str, tone: str = "") -> None: ...

    # Today
    def day_shift(self, days: int) -> None: ...
    def day_today(self) -> None: ...
    def day_menu(self, anchor: Any) -> None: ...

    # Me: corrections in the user's own words
    def correct_item(self, item: Any, words: str) -> None: ...
    def forget_item(self, item: Any) -> None: ...
    def confirm_item(self, item: Any) -> None: ...
    def refresh_portrait(self) -> None: ...

    # Yuki
    def revoke_rule(self, ref: str) -> None: ...
    def add_rule(self, text: str) -> None: ...
    def answer_question(self, ref: str, words: str) -> None: ...
    def skip_question(self, ref: str, never: bool) -> None: ...

    # Status
    def erase_calls(self) -> None: ...
    def stop_call(self) -> None: ...
    def snooze(self, minutes: int) -> None: ...
    def start_memory(self) -> None: ...

    # Settings (and Status rows that toggle the same things)
    def set_paused(self, paused: bool) -> None: ...
    def set_wake(self, on: bool) -> None: ...
    def set_device(self, kind: str, name: str | None) -> None: ...
    def device_options(self, kind: str) -> list[tuple[str, Any]]:
        return []
    def set_voice_id(self, voice_id: str) -> None: ...
    def set_coach(self, on: bool) -> None: ...
    def set_quiet(self, start: str, end: str) -> None: ...
    def set_questions(self, on: bool) -> None: ...
    def set_call_pref(self, app: str, decision: str | None) -> None: ...
    def add_blocked(self, kind: str, value: str) -> None: ...
    def remove_blocked(self, kind: str, value: str) -> None: ...
    def set_startup(self, on: bool) -> None: ...
    def set_appearance(self, mode: str) -> None: ...
    def set_glass(self, mode: str) -> None: ...
    def set_bend(self, value: float) -> None: ...
    def set_blur(self, value: float) -> None: ...
    def set_reduce_motion(self, on: bool) -> None: ...
    def set_model(self, alias: str) -> None: ...
    def set_effort(self, level: str) -> None: ...
    def open_logs(self) -> None: ...

    # Chat
    def submit(self, text: str) -> None: ...
    def cancel(self) -> None: ...
    def reply_nudge(self, nudge: dict) -> None: ...

    # live state the pages show (the controller keeps it current)
    connected: bool = False
    ui: Any = None


NOOP = Actions()


def correction_text(subject: str, memory_had: str, words: str) -> str:
    """How a correction from the Me page reaches memory: the user's own words, and what they answer.

    ``About "<subject>" (memory had: "<text>"), the user said in their own words: "<words>"``
    (docs/UI-window.md, Me page). The portrait's fold decides what it changes.
    """
    return (f'About "{subject}" (memory had: "{" ".join(memory_had.split())}"), the user said in their own words: '
            f'"{" ".join(words.split())}"')
