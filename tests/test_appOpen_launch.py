class _Params:
    def __init__(self, name: str, args: dict[str, Any]) -> None:
        self.function_name, self.arguments, self.tool_call_id = name, args, f"call-{name}"
        self.results: list[dict[str, Any]] = []
        self.spoken: list[str] = []

        async def push_frame(frame: Any) -> None:
            self.spoken.append(frame.text)

        self.llm = SimpleNamespace(push_frame=push_frame)

    async def result_callback(self, result: dict, properties: Any = None) -> None:
        self.results.append(result)


class _Memory:
    session_id = "s-test"

    def __init__(self) -> None:
        self.acting: list[tuple[str, str]] = []
        self.runs: list[dict[str, Any]] = []
        self.hand_traces: list[dict[str, Any]] = []

    def acting_begin(self, token: str, request: str, *, lane: str = "") -> bool:
        self.acting.append(("begin", token))
        return True

    def acting_end(self, token: str) -> bool:
        self.acting.append(("end", token))
        return True

    def record_run(self, run: dict[str, Any], **_k: Any) -> bool:
        self.runs.append(run)
        return True

    def record_hand_trace(self, **kw: Any) -> bool:
        self.hand_traces.append(kw)
        return True


def _hands(details: dict[str, Any], *, ok: bool = True, watch: Any = None) -> Any:
    from yuki.voice.hands import Hands
    from yuki.voice.offline import BrowserDesk, StubResult

    desk = BrowserDesk(action_delay_s=0)
    desk.launch_app = lambda query, **kw: StubResult(ok=ok, summary=f"report for {query}", details=dict(details))
    if watch is not None:
        desk.watch_launch = watch
    hands = Hands(desk)
    hands.memory = _Memory()
    hands.words = lambda: ["open starfall"]
    hands.turn_key = lambda: "s-test-3"
    hands.shown = lambda: []
    return hands


def _wait(cond: Any, timeout: float = 3.0) -> bool:
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        if cond():
            return True
        time.sleep(0.01)
    return bool(cond())


def test_the_hand_says_starting_watches_and_keeps_the_opening_with_its_outcome() -> None:
    from yuki.voice.workers import ordered

    launcher = {"name": "Starfall", "appid": "x", "carrier_exe": CARRIER, "carrier": "Fake Launcher"}
    seen: list[dict] = []

    def watch(info: dict, *, stop: Any = None) -> dict:
        seen.append(info)
        return {"verified": True, "summary": "Starfall's own window is up after 80 s", "process_name":
                "starfall-win64-shipping.exe", "in_front": True, "fullscreen": True}

    hands = _hands({"verified": None, "starting": True, "launcher": launcher, "hwnd": None}, watch=watch)
    hands.snapshot()
    p = _Params("open_app", {"name": "Starfall", "say_first": "Opening it.", "say_when_done": "Done.", "then": ""})
    asyncio.run(hands.handle(p))
    assert p.spoken == []                                                  # never "Done." for a game still starting
    assert "starting" in p.results[0] and "never say it is open" in p.results[0]["how_to_say_it"]
    assert _wait(lambda: hands.memory.runs)
    ordered().submit(lambda: None)
    assert seen == [launcher] and hands.watched[-1]["verified"] is True
    run = hands.memory.runs[-1]
    assert [s["verdict"] for s in run["steps"]] == [None, True] and run["outcome"] == "final"
    assert run["steps"][1]["app"] == "starfall-win64-shipping.exe" and hands.memory.hand_traces == []
    assert [a for a, _t in hands.memory.acting] == ["begin", "end"]       # the hand's effect is Yuki's
    assert "watched Starfall start" in hands.actions.text()               # the talker's desk sees the outcome


