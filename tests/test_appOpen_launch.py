def test_the_thinker_reads_launch_apps_own_verdict_and_can_wait_for_a_slow_game() -> None:
    from yuki.agent.loop import action_verdict
    from yuki.agent.tools import LAUNCH_WAIT_MAX_S, Dispatcher, ToolOutcome

    def outcome(details: dict) -> ToolOutcome:
        return ToolOutcome(name="launch_app", ok=True, summary="", payload={"ok": True, "details": details})

    assert action_verdict("launch_app", outcome({"verified": True, "hwnd": 1}))[0] is True
    assert action_verdict("launch_app", outcome({"verified": False, "hwnd": 1}))[0] is False
    verdict, why = action_verdict("launch_app", outcome({"verified": None, "starting": True}))
    assert verdict is None and "still starting" in why
    assert action_verdict("launch_app", outcome({"hwnd": 1}))[0] is True      # an old report: as before
    calls: list[dict] = []

    class Backend:
        def launch_app(self, query: str, **kw: Any) -> Any:
            calls.append(kw)
            return SimpleNamespace(ok=True, summary="", details={"verified": None, "starting": True},
                                   elapsed_ms=1.0)

    dispatcher = Dispatcher(Backend())
    dispatcher._do_launch_app({"query": "Starfall", "wait_s": 500})
    dispatcher._do_launch_app({"query": "Starfall"})
    assert calls == [{"timeout_s": float(LAUNCH_WAIT_MAX_S)}, {}]


