class World:
    """An invented desktop: processes, user windows, the window in front, and what starting an entry does."""

    def __init__(self) -> None:
        self.procs: dict[int, L._Proc] = {}
        self.windows: list[SimpleNamespace] = []
        self.foreground = 0
        self.started: list[str] = []
        self.on_start: Any = None
        self.polls = 0
        self.on_poll: list[tuple[int, Any]] = []
        self.forwarded: list[int] = []

    def proc(self, pid: int, exe: str, ppid: int = 0, created: float = 1000.0) -> None:
        import os

        self.procs[pid] = L._Proc(pid, ppid, os.path.normcase(exe), os.path.basename(exe).lower(), created)

    def window(self, hwnd: int, pid: int, title: str, *, front: bool = False, fullscreen: bool = False) -> None:
        import os

        exe = self.procs[pid].exe
        self.windows.append(SimpleNamespace(hwnd=hwnd, pid=pid, title=title, process_name=os.path.basename(exe),
                                            is_fullscreen=fullscreen))
        if front:
            self.foreground = hwnd

    def user_windows(self) -> list:
        self.polls += 1
        for at, fn in list(self.on_poll):
            if self.polls >= at:
                self.on_poll.remove((at, fn))
                fn()
        return list(self.windows)


